#include <stdio.h>   /* Standard I/O library for printf() */

int main()           /* Main function - program starts executing here */
{
    printf("My name is Manan Rami\n");          /* Print name, \n moves to next line. */
    printf("I am 19 years old\n");               /* Print age (no \n, stays on same line) */
    printf("I live in Ahmedabad\n");            /* Print city, \n moves to next line */
    printf("I love watching formula 1 racing\n"); /* Print hobby */

    return 0;   /* Return 0 = program ran successfully, no errors */
}
